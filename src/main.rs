//a vertex shader module generated by a crazy macro
//contains functions for compiling it on a gpu virtual machine
//executes for each vertex in a draw command
mod vs { 
    vulkano_shaders::shader! {
        ty: "vertex",
        src: r"
            #version 460

            layout(location = 0) in vec2 position;
            layout(location = 1) in vec2 uv;
            layout(location = 0) out vec2 fragCoord;

            void main() {
                fragCoord = uv;
                gl_Position = vec4(position, 0.0, 1.0);
            }
        ",
    }
}

