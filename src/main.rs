static WINDOW_INIT_WIDTH : u32 = 600;
static WINDOW_INIT_HEIGHT : u32 = 400;

fn main() {
    
    let event_loop: EventLoop<UserEvent> = EventLoop::<UserEvent>::with_user_event().build().unwrap();
    //proxy loop used to send custom UserEvents
    //allows multiple threads to interact with the application
    let proxy_loop: winit::event_loop::EventLoopProxy<UserEvent> = event_loop.create_proxy();

    let vulkan_driver = initialize_vulkano(&event_loop);

    //The application stores all the data the application needs to run, 
    //most of them are optional, set to None since we can't initialize them until the window is made
    let mut render_app: Application = Application {
        vk_driver: vulkan_driver,
        event_loop_proxy: Some(Arc::new(RwLock::new(proxy_loop))),
        window_create_info: Window::default_attributes() //data window initially starts out with
            .with_blur(false)
            .with_inner_size(LogicalSize::new(WINDOW_INIT_WIDTH, WINDOW_INIT_HEIGHT))
            .with_resizable(true)
            .with_title(String::from_str("Test Renderer").unwrap())
            .with_maximized(false)
            .with_visible(true)
            .with_transparent(false),
        ..Default::default()
    };
    //This will internally call the impl application handler resumed() function and start the application
    event_loop.run_app(&mut render_app).unwrap();
    //all application behavior is done through the applicationHandler trait
}

